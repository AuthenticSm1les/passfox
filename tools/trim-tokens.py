#!/usr/bin/env python3
"""Write extension/vendor/firefox/tokens-ui.css: Firefox's design tokens
(tokens-shared.css + tokens-platform.css) cut down to the ones passfox's
in-page UI and toolbar panel use, directly or through other tokens.

Pages get this stylesheet in every shadow root that shows the dropdown or
the save prompt, so it's kept small; the passwords and preferences pages use
Firefox's full files.

  python3 -I tools/trim-tokens.py           # regenerate
  python3 -I tools/trim-tokens.py --check   # fail if it's out of date (CI)
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "extension"
VENDOR = ROOT / "vendor/firefox"
SOURCES = [VENDOR / "tokens-shared.css", VENDOR / "tokens-platform.css"]
OUT = VENDOR / "tokens-ui.css"
# Everything that renders with tokens-ui.css and may name a token.
USERS = ["shared/firefox.css", "popup/popup.css", "shared/*.js", "content/*.js", "popup/*.js"]

DECL = re.compile(r"\s*(--[\w-]+)\s*:[^;{}]*;")
VAR = re.compile(r"var\(\s*(--[\w-]+)")
EMPTY_BLOCK = re.compile(r"\n?[^{};]*\{\s*\}")
SECTION = re.compile(r"\n\s*/\*\*[^*]*\*\*/")  # /** border **/ headings
BLANK = re.compile(r"\n\s*\n")


def used_tokens(css):
    values = {}
    for match in DECL.finditer(css):
        values.setdefault(match.group(1), []).append(match.group(0))
    pending = [name for pattern in USERS for path in ROOT.glob(pattern) for name in VAR.findall(path.read_text())]
    used = set()
    while pending:
        name = pending.pop()
        if name not in used:
            used.add(name)
            for value in values.get(name, []):
                pending += VAR.findall(value)
    return used


def trim(css, used):
    css = DECL.sub(lambda m: m.group(0) if m.group(1) in used else "", css)
    css = SECTION.sub("", css)
    while True:
        shorter = EMPTY_BLOCK.sub("", css)
        if shorter == css:
            return BLANK.sub("\n", css)
        css = shorter


def build():
    texts = [path.read_text() for path in SOURCES]
    used = used_tokens("\n".join(texts))
    header = "/* Generated by tools/trim-tokens.py from tokens-shared.css and tokens-platform.css. */\n"
    return header + "\n".join(trim(text, used) for text in texts)


def main():
    css = build()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != css:
            sys.exit(f"{OUT.relative_to(ROOT.parent)} is out of date: run python3 -I tools/trim-tokens.py")
        return
    OUT.write_text(css)
    print(f"tokens-ui.css: {len(css)} bytes (from {sum(p.stat().st_size for p in SOURCES)})")


if __name__ == "__main__":
    main()
