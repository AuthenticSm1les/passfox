#!/usr/bin/env python3
"""Build extension/shared/icons.js from the vendored Firefox SVG icons.

Keeps the Nova artwork (Firefox 158's default design; Proton where an icon
has no Nova variant) and swaps Firefox's chrome-only context-fill for
currentColor so the icons follow the surrounding text colour. Also writes the
toolbar icons, which need fixed fills.
"""

import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent / "extension"
src = root / "vendor" / "firefox" / "icons"
icons = {}
for svg in sorted(src.glob("*.svg")):
    text = svg.read_text()
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text = re.sub(r"<style>.*?</style>", "", text, flags=re.S)
    if '<g class="nova">' in text:
        text = re.sub(r'<g class="proton">.*?</g>', "", text, flags=re.S)
    text = text.replace('fill="context-fill"', 'fill="currentColor"')
    text = re.sub(r'\s*fill-opacity="context-fill-opacity"', "", text)
    text = re.sub(r">\s+<", "><", text).strip()
    icons[svg.stem] = text

out = root / "shared" / "icons.js"
out.write_text(
    "/* Generated by tools/gen-icons.py from Firefox icons.\n"
    " * This Source Code Form is subject to the terms of the Mozilla Public\n"
    " * License, v. 2.0. If a copy of the MPL was not distributed with this\n"
    " * file, You can obtain one at http://mozilla.org/MPL/2.0/. */\n\n"
    f"globalThis.PASSFOX_ICONS = {json.dumps(icons, indent=2)};\n"
)
print(f"wrote {len(icons)} icons to {out}")

# WebExtension toolbar icons can't use context-fill: one per theme brightness.
for name, color in (("login-dark.svg", "#5b5b66"), ("login-light.svg", "#fbfbfe")):
    (root / "icons" / name).write_text(icons["login"].replace('fill="currentColor"', f'fill="{color}"'))
